/**
 * Processor and large off-taker: procurement, company, contracts, inspections.
 *
 * PROCUREMENT IS NOT SHOPPING
 *   A processor does not add things to a cart. They post a BUY REQUEST, which
 *   suppliers BID on; the processor AWARDS a bid, which becomes a CONTRACT,
 *   against which goods are inspected, moved and settled. Each of those is a
 *   distinct state with distinct consequences, and translating any two of them
 *   to the same word would make the pipeline unreadable.
 *
 *   `rfqs` is the route slug and the database's word. The interface says "buy
 *   request" because that is what a Nigerian processor calls it, and the two
 *   must not be reconciled by renaming either one.
 *
 * MONEY LANGUAGE CARRIES THE SAME RULES AS EVERYWHERE ELSE
 *   Escrow is held by a licensed payment partner, never by Loamy. Financing
 *   decisions belong to partner banks. Funding an escrow and releasing it are
 *   two different facts about where money is, and a translation that merges
 *   them tells a supplier they have been paid when nothing has moved.
 *
 * WHAT STAYS AS DATA
 *   Company names, supplier names, commodity names, quantities, units, prices,
 *   RC/BN and TIN numbers, document filenames and every reference. These are
 *   interpolated, never translated.
 */
