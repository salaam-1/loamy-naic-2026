/**
 * The bank portal: the interface a lending officer works in.
 *
 * LOAMY IS NOT THE LENDER, AND THIS VOCABULARY IS WHERE THAT IS EASIEST TO LOSE
 *   A bank officer reads these words while recording a decision about somebody
 *   else's money. Every one of them has to keep four facts straight:
 *
 *     - the BANK decides. Loamy records what the bank decided and never
 *       approves, declines or prices anything.
 *     - Loamy holds no funds. Disbursement and settlement happen on the bank's
 *       own rails, off-platform. A "portfolio" figure here is a mirrored
 *       record, not a balance Loamy controls.
 *     - an APPROVED amount is not a disbursed amount. They are different
 *       columns and different events, and a translation that merges them tells
 *       an officer money has moved when it has not.
 *     - a REQUESTED amount is what an applicant asked for. It is not a promise,
 *       not an offer, and not an entitlement.
 *
 * THE STATUS VOCABULARY IS NOT HERE
 *   `financing.status.*` already carries all thirteen statuses the check
 *   constraint permits, and `financing.statusHint.*` carries what each one
 *   means to an applicant. Those are reused, never re-coined: a second set of
 *   words for the same thirteen states is how a portal and a dashboard end up
 *   disagreeing about one row.
 *
 * WHAT STAYS AS DATA
 *   Applicant and company names, bank names, digital IDs, facility and
 *   application references, account and transaction refs, addresses, uploaded
 *   document names, officer notes and the bank's own reference. Interpolated,
 *   never translated.
 */
